-- Tenant migration 023: Real ICD-10 (CIE-10) diagnosis catalog.
--
-- Replaces the free-text CIE-10 inputs previously accepted on
-- Diagnosis.PrimaryCode/Related*Code (docs/GAP_ANALYSIS_HISTORIA_CLINICA_JARVIS.md,
-- section 03/08). Diagnosis.PrimaryCode itself stays VARCHAR(20) — connected
-- to this catalog via application-level validation
-- (clinicalrecord.Service.validateIcd10Code), not a hard DB FK, so existing
-- diagnoses rows are never invalidated by a schema change.
--
-- Seed scope: WHO ICD-10 Chapter VII (Diseases of the eye and adnexa,
-- H00-H59) plus the Z00-series codes used for routine/screening visits —
-- the codes actually relevant to an optometry practice. This is a real,
-- accurate subset (not the full ~14,000-entry national CIE-10 table); more
-- chapters can be loaded later (e.g. via bulk import) without any schema
-- change if a future need requires diagnoses outside ophthalmology.

CREATE TABLE IF NOT EXISTS icd10_codes (
    id          BIGSERIAL     PRIMARY KEY,
    code        VARCHAR(10)   NOT NULL,
    description TEXT          NOT NULL,
    chapter     VARCHAR(10),
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_icd10_codes_code ON icd10_codes(code);
CREATE INDEX IF NOT EXISTS idx_icd10_codes_active ON icd10_codes(is_active) WHERE is_active = true;

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX IF NOT EXISTS idx_icd10_codes_description_trgm
    ON icd10_codes USING GIN (description gin_trgm_ops);

